// ───────── Lookup Helpers ─────────

export const GEONODE_BY_SLUG: Record<string, GeoNode> = Object.fromEntries(
  GEONODES.map((g) => [g.slug, g])
);

export const GEONODE_BY_ID: Record<string, GeoNode> = Object.fromEntries(
  GEONODES.map((g) => [g.id, g])
);

export function getGeoNode(slug: string): GeoNode | undefined {
  return GEONODE_BY_SLUG[slug];
}

export function getGeoNodesByTier(tier: GeoTier): GeoNode[] {
  return GEONODES.filter((g) => g.tier === tier);
}

export function getGeoCountries(): GeoNode[] {
  return GEONODES.filter((g) => !g.isRegion);
}

export function getGeoRegions(): GeoNode[] {
  return GEONODES.filter((g) => g.isRegion);
}

export const GEOCOUNTRIES: GeoNode[] = getGeoCountries();
export const GEOREGIONS: GeoNode[] = getGeoRegions();
